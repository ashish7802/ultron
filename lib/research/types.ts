/**
 * @file lib/research/types.ts
 * @description Strongly-Typed Contracts & Schemas for the ULTRON Research & Verification Engine.
 *
 * Subsystem:
 * Research Foundation, Planning, Multi-Source Discovery & Traceable Evidence Extraction.
 *
 * Key Responsibilities:
 * - Defines structured representations for Research Plans, Sub-questions, Scope, and Intent.
 * - Outlines normalized contracts for Multi-Provider Discovery (Web, GitHub, Academic, Docs, News, Memory).
 * - Establishes atomic data schemas for Extracted Claims, Structured Facts, Technical Specs, and Verbatim Passages.
 * - Enforces many-to-many relationship structures linking Research Projects -> Sources -> Evidence -> Claims.
 *
 * Architectural Role & Interactions:
 * - Serves as the central data contract for:
 *   - Module 01: `lib/research/planningEngine.ts`
 *   - Module 02: `lib/research/discoveryEngine.ts`
 *   - Module 03: `lib/research/evidenceEngine.ts`
 *   - Persistence: `lib/research/repository.ts`
 *   - Unified Pipeline: `lib/research/orchestrator.ts`
 *   - Next.js API Routes: `app/api/research/*`
 *
 * Safety / Security Guarantees:
 * - Read-only typing: Immutable data contracts preventing unauthorized mutation.
 * - Source traceability: Every extracted claim and fact strictly references its origin URL, hash, and timestamp.
 * - Untrusted external content isolation: Raw external HTML/text is decoupled from execution directives.
 */

