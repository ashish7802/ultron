// MODULE 02: INFORMATION DISCOVERY CONTRACTS
// ==============================================================================

/**
 * Recognized source classifications arranged according to the 6-tier credibility hierarchy.
 */
export type SourceType =
  | "official_documentation"     // Tier 1: Primary doc, language/framework specs
  | "technical_specification"    // Tier 2: RFCs, IEEE, W3C standards
  | "academic_paper"             // Tier 2: Peer-reviewed arXiv, Semantic Scholar, CrossRef
  | "github_repository"          // Tier 3: Official GitHub repositories, release tags
  | "api_documentation"          // Tier 1/3: Public API documentation, Swagger/OpenAPI
  | "reputable_publication"      // Tier 4: Engineering blogs, high-authority tech outlets
  | "independent_analysis"       // Tier 5: Independent developer benchmarks and write-ups
  | "community_discussion"       // Tier 6: Forums, StackOverflow, Reddit (signals, not facts)
  | "news_release"               // Tier 4: Official changelogs, vendor security announcements
  | "internal_document"          // Internal: Local documentation and workspace specs
  | "advanced_memory"            // Internal: ULTRON memory vault & previous research archives
  | "web_general";               // General web fallback

/**
 * Retrieval status of a discovered source.
 */
export type DiscoveryRetrievalStatus =
  | "discovered"
  | "fetched"
  | "cached"
  | "failed"
  | "restricted"
  | "timeout";

/**
 * Content availability description after discovery.
 */
export type ContentAvailability =
  | "unfetched"
  | "full_text"
  | "snippet_only"
  | "inaccessible";

/**
 * Normalized output contract returned by every Discovery Provider Adapter.
 */
export interface NormalizedDiscoveryResult {
  discovery_id: string;
  research_id: string;
  query_id?: string;
  title: string;
  original_url: string;
  canonical_url?: string;
  snippet: string;
  source_type: SourceType;
  publisher?: string;
  author?: string;
  publication_date?: string; // ISO 8601 string
  discovered_at: string;     // ISO 8601 string
  provider: string;          // ddgs, github, academic, docs, news, internal_docs, memory
  provider_metadata: Record<string, unknown>;
  content_availability: ContentAvailability;
  retrieval_status: DiscoveryRetrievalStatus;
  priority_tier: number;     // 1 to 6 (1 = highest authority)
  relevance_score: number;   // 0.0 to 1.0
}

/**
 * Input query specification delivered to Discovery Adapters.
 */
export interface DiscoveryQueryInput {
  researchId: string;
  queryId: string;
  searchObjective: string;
  primaryQuery: string;
  alternativeQueries?: string[];
  preferredSourceTypes?: SourceType[];
  officialDomains?: string[];
  maxResults?: number;
  requiredDateRange?: {
    startYear?: number;
    endYear?: number;
  };
}

/**
 * Base interface that every Discovery Adapter must implement.
 */
export interface SearchProviderAdapter {
  readonly providerName: string;
  readonly isConfigured: boolean;
  discover(input: DiscoveryQueryInput): Promise<NormalizedDiscoveryResult[]>;
  healthCheck(): Promise<{ available: boolean; latencyMs?: number; message?: string }>;
}

