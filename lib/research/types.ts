/**
 * Supported structured content formats extracted from discovered sources.
 */
export type SourceContentType =
  | "html"
  | "markdown"
  | "github_readme"
  | "release_notes"
  | "api_documentation"
  | "pdf"
  | "plain_text";

/**
 * Raw or cleaned content retrieved from a source URL.
 */
export interface SourceContent {
  sourceId: string;
  originalUrl: string;
  canonicalUrl?: string;
  contentType: SourceContentType;
  rawText: string;
  cleanText: string;
  title: string;
  headings: string[];
  contentHash: string; // SHA-256 for duplicate and drift detection
  byteLength: number;
  fetchedAt: string;
  httpStatus: number;
}

/**
 * Atomic claim extracted from gathered evidence passages.
 */
export interface ExtractedClaim {
  id: string;
  researchId: string;
  sourceId: string;
  claimText: string;
  claimType:
    | "feature_capability"
    | "architectural_spec"
    | "version_requirement"
    | "performance_benchmark"
    | "compatibility_constraint"
    | "general_fact";
  subject: string;
  predicate: string;
  objectValue: string;
  contextQualifier?: string;
  confidenceScore: number; // 0.0 to 1.0 extraction confidence
  extractedAt: string;
}

/**
 * Structured technical specification item.
 */
export interface TechnicalSpecification {
  category: "version" | "hardware" | "software" | "api" | "performance" | "configuration" | "limitation";
  name: string;
  value: string;
  unit?: string;
  minimum?: string;
  recommended?: string;
  sourcePassage: string;
}

/**
 * Structured fact item.
 */
export interface ExtractedFact {
  factKey: string;
  factValue: string;
  category: "date" | "version" | "metric" | "name" | "dependency" | "limitation";
  supportingPassage: string;
  confidence: number;
}

/**
 * Detailed version and temporal timestamp metadata extracted from source.
 */
export interface ExtractedVersionDate {
  publicationDate?: string;
  lastUpdatedDate?: string;
  releaseDate?: string;
  softwareVersion?: string;
  apiVersion?: string;
  documentRevision?: string;
  accessDate: string;
}

/**
 * Exact verbatim supporting passage with byte/character offsets.
 */
export interface SupportingPassage {
  id: string;
  researchId: string;
  sourceId: string;
  exactText: string;
  surroundingContext?: string;
  sectionHeading?: string;
  pageNumber?: number;
  chunkIndex: number;
  charOffsetStart: number;
  charOffsetEnd: number;
  evidenceType: "passage" | "technical_spec" | "version_date" | "benchmark";
  structuredData?: Record<string, unknown>;
  contentHash: string; // SHA-256 of exact text
  extractedAt: string;
}

/**
 * Many-to-many junction relationship between an atomic claim and supporting evidence passage.
 */
export interface ClaimEvidenceLink {
  id: string;
  claimId: string;
  evidenceId: string;
  relationshipType: "supports" | "provides_context" | "mentions";
  relevanceScore: number;
  createdAt: string;
}

/**
 * Outcome of duplicate source detection.
 */
export interface DuplicateDetectionResult {
  isDuplicate: boolean;
  duplicateType: "exact_duplicate" | "url_variation" | "updated_version" | "syndicated_copy" | "independent_source";
  existingSourceId?: string;
  similarityScore: number; // 0.0 to 1.0
  reason: string;
}

/**
 * Combined output contract for Module 03 evidence extraction.
 */
export interface EvidenceExtractionResult {
  researchId: string;
  sourceId: string;
  sourceUrl: string;
  canonicalUrl?: string;
  contentAvailable: boolean;
  duplicateCheck: DuplicateDetectionResult;
  versionDates: ExtractedVersionDate;
  passages: SupportingPassage[];
  facts: ExtractedFact[];
  specifications: TechnicalSpecification[];
  claims: ExtractedClaim[];
  claimEvidenceLinks: ClaimEvidenceLink[];
  extractionDurationMs: number;
  extractionStatus: "success" | "partial" | "failed";
  errorMessage?: string;
}

